#!/usr/bin/env python3
"""Makes /ru/index.html and /en/index.html from index.html (the Azerbaijani page) and refreshes sitemap.xml.
Run after every change to index.html:   python3 build.py
Each language gets its own address so Google can index all three."""
import re, datetime, pathlib

ROOT = pathlib.Path(__file__).parent
SITE = "https://svetlanatbaytarliq.com"
src = (ROOT / "index.html").read_text(encoding="utf-8")

PAGES = {
  "ru": dict(
    title="Ветеринарная клиника Svetlana-T — Баку | Ветеринар, прививки, УЗИ",
    desc="Ветеринарная клиника Svetlana-T, Баку: осмотр, прививки, УЗИ, анализы, стерилизация и хирургия для кошек и собак. Ветаптека и корма. Онлайн-запись: 050 653 08 77",
    og="Ветеринарная клиника Svetlana-T — Баку", locale="ru_RU"),
  "en": dict(
    title="Svetlana-T Veterinary Clinic — Baku | Vet, vaccinations, ultrasound",
    desc="Svetlana-T veterinary clinic in Baku: check-ups, vaccinations, ultrasound, lab tests, spaying and surgery for cats and dogs. Vet pharmacy and pet food. Book online: 050 653 08 77",
    og="Svetlana-T Veterinary Clinic — Baku", locale="en_US"),
}

def sub1(pattern, repl, text):
    new, n = re.subn(pattern, repl, text, count=1, flags=re.S)
    assert n == 1, pattern
    return new

for code, p in PAGES.items():
    url = f"{SITE}/{code}/"
    h = src
    h = sub1(r'<html lang="az">', f'<html lang="{code}">', h)
    h = sub1(r'<title>.*?</title>', f'<title>{p["title"]}</title>', h)
    h = sub1(r'<meta name="description" content="[^"]*">', f'<meta name="description" content="{p["desc"]}">', h)
    h = sub1(r'<link rel="canonical" href="[^"]*">', f'<link rel="canonical" href="{url}">', h)
    h = sub1(r'<meta property="og:url" content="[^"]*">', f'<meta property="og:url" content="{url}">', h)
    h = sub1(r'<meta property="og:title" content="[^"]*">', f'<meta property="og:title" content="{p["og"]}">', h)
    h = sub1(r'<meta property="og:description" content="[^"]*">', f'<meta property="og:description" content="{p["desc"]}">', h)
    h = sub1(r'<meta property="og:locale" content="[^"]*">', f'<meta property="og:locale" content="{p["locale"]}">', h)
    h = sub1(r"<!DOCTYPE html>\n", "<!DOCTYPE html>\n<!-- GENERATED by build.py from /index.html — edit index.html, then run: python3 build.py -->\n", h)
    (ROOT / code).mkdir(exist_ok=True)
    (ROOT / code / "index.html").write_text(h, encoding="utf-8")

today = datetime.date.today().isoformat()
alts = "".join(f'\n    <xhtml:link rel="alternate" hreflang="{c}" href="{SITE}{u}"/>' for c, u in [("az","/"),("ru","/ru/"),("en","/en/"),("x-default","/")])
urls = "".join(f'\n  <url>\n    <loc>{SITE}{u}</loc>\n    <lastmod>{today}</lastmod>{alts}\n  </url>' for u in ["/", "/ru/", "/en/"])
(ROOT / "sitemap.xml").write_text(f'<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">{urls}\n</urlset>\n', encoding="utf-8")
print("built: /ru/ /en/ + sitemap.xml")
